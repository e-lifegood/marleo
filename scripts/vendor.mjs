// Copies the browser bundles mdv needs from node_modules into web/vendor
// and writes THIRD_PARTY_NOTICES.md with the exact versions and licenses.
//
// Usage:  npm ci && npm run vendor
import { copyFileSync, mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const nm = join(root, "node_modules");
const out = join(root, "web", "vendor");
mkdirSync(join(out, "hljs"), { recursive: true });

/** [package, file inside package, destination inside web/vendor] */
const files = [
  ["markdown-it", "dist/markdown-it.min.js", "markdown-it.min.js"],
  ["dompurify", "dist/purify.min.js", "purify.min.js"],
  ["@highlightjs/cdn-assets", "highlight.min.js", "hljs/highlight.min.js"],
  ["@highlightjs/cdn-assets", "languages/powershell.min.js", "hljs/powershell.min.js"],
  ["@highlightjs/cdn-assets", "languages/dockerfile.min.js", "hljs/dockerfile.min.js"],
  ["@highlightjs/cdn-assets", "languages/nginx.min.js", "hljs/nginx.min.js"],
  ["@highlightjs/cdn-assets", "languages/http.min.js", "hljs/http.min.js"],
  ["@highlightjs/cdn-assets", "languages/latex.min.js", "hljs/latex.min.js"],
  ["@highlightjs/cdn-assets", "languages/protobuf.min.js", "hljs/protobuf.min.js"],
  ["@highlightjs/cdn-assets", "languages/graphql.min.js", "hljs/graphql.min.js"],
  ["mermaid", "dist/mermaid.min.js", "mermaid.min.js"],
];

const notices = new Map();
for (const [pkg, src, dest] of files) {
  const from = join(nm, pkg, src);
  if (!existsSync(from)) {
    console.error(`missing ${from} - did you run "npm ci"?`);
    process.exit(1);
  }
  copyFileSync(from, join(out, dest));
  console.log(`vendor/${dest}`);

  if (!notices.has(pkg)) {
    const meta = JSON.parse(readFileSync(join(nm, pkg, "package.json"), "utf8"));
    const licenseFile = ["LICENSE", "LICENSE.md", "LICENSE.txt"].map((f) => join(nm, pkg, f)).find(existsSync);
    notices.set(pkg, {
      version: meta.version,
      license: meta.license,
      homepage: meta.homepage,
      text: licenseFile ? readFileSync(licenseFile, "utf8").trim() : "",
    });
  }
}

let md = "# Third-party notices\n\nmdv bundles the following open-source libraries (generated by `scripts/vendor.mjs`).\n";
for (const [pkg, n] of notices) {
  md += `\n## ${pkg} ${n.version}\n\nLicense: ${n.license}${n.homepage ? ` - ${n.homepage}` : ""}\n`;
  if (n.text) md += "\n```text\n" + n.text + "\n```\n";
}
writeFileSync(join(root, "THIRD_PARTY_NOTICES.md"), md);
console.log("THIRD_PARTY_NOTICES.md");
